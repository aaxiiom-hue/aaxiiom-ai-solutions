import type { BusinessProblem, Industry, SolutionCategorySlug } from "./types";

/**
 * Compact tuple format so new industries and problems can be added quickly
 * without touching any UI component.
 *
 * [area, title, problem, whyItMatters, possibleSolution, category, solutionSlug,
 *  howItWorks, benefits, workflow, integrations]  -- pipe separated lists
 */
type ProblemTuple = [
  string,
  string,
  string,
  string,
  string,
  SolutionCategorySlug,
  string,
  string,
  string,
  string,
  string,
];

const slugify = (value: string) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const list = (value: string) => value.split("|").map((item) => item.trim());

const problem = (tuple: ProblemTuple): BusinessProblem => ({
  slug: slugify(tuple[1]),
  area: tuple[0],
  title: tuple[1],
  problem: tuple[2],
  whyItMatters: tuple[3],
  possibleSolution: tuple[4],
  category: tuple[5],
  solutionSlug: tuple[6],
  howItWorks: list(tuple[7]),
  benefits: list(tuple[8]),
  workflow: list(tuple[9]),
  integrations: list(tuple[10]),
});

interface IndustryDef {
  slug: string;
  name: string;
  icon: string;
  overview: string;
  automationOpportunities: string[];
  problems: ProblemTuple[];
}

